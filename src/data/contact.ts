import data from './contact-audit.json';
export type Language = 'en' | 'de' | 'ru';
export type ContactRecord = (typeof data.records)[number];
export const contactAudit = data;
export const contacts: Record<string, ContactRecord> = Object.fromEntries(
  data.records.map((r) => [r.id, r]),
);
export const contactIssues: Record<string, { status: string; en: string; de: string; ru: string }> =
  data.issues;
export function contactName(entry: { id: string; english: string }, language: Language) {
  return contacts[entry.id]?.names[language] ?? entry.english;
}
export function contactSearch(id: string) {
  const r = contacts[id];
  return r ? Object.values(r.names).join(' ') : '';
}
